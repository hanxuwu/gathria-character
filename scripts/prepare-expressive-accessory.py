"""Deterministically prepare the AI-authored ornament for the runtime layer bank.
Technical alpha extraction and nearest-neighbor sizing only; no redraw.
"""
from pathlib import Path
import base64, json, zlib
import numpy as np
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
source = Image.open(ROOT / 'artwork/expressive-source/flower-clip.png').convert('RGBA')
alpha = source.getchannel('A').point(lambda a: 255 if a >= 128 else 0)
source.putalpha(alpha)
source = source.crop(alpha.getbbox())
source.thumbnail((28, 40), Image.Resampling.NEAREST)
pixels = np.array(source)
pixels[pixels[:,:,3] == 0] = 0
packed = np.zeros((source.height,source.width,5),dtype=np.uint8)
packed[:,:,:4] = pixels
layer = dict(id='v4-flower-clip',x=53,y=40,width=source.width,height=source.height,palette={},data=base64.b64encode(zlib.compress(packed.tobytes(),9)).decode())
(ROOT/'src/core/expressive-accessory.generated.ts').write_text('// Generated by scripts/prepare-expressive-accessory.py; do not edit.\nimport type { IllustratedLayer } from "./illustrated-types";\nexport const FLOWER_CLIP: IllustratedLayer = '+json.dumps(layer,separators=(',',':'))+';\n')
print(f'Prepared {source.width}x{source.height} flower clip')
